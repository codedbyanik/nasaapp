'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../..'),O=require('../../src/features/observations.js'),P=require('../../src/core/planner.js');
const catalog=JSON.parse(fs.readFileSync(path.join(root,'data/processed/nasa/observations.json')));
P.setDataset(JSON.parse(fs.readFileSync(path.join(root,'data/processed/nasa/terrain_grid.json'))));
const polygon={type:'Polygon',coordinates:[[[0,0],[4,0],[4,4],[0,4],[0,0]],[[1,1],[2,1],[2,2],[1,2],[1,1]]]};
assert(O.contains([.5,.5],polygon));assert(!O.contains([1.5,1.5],polygon));assert(!O.contains([5,2],polygon));
const landing=O.matches(P.DEFAULT_START,catalog);assert(landing.length>0);assert.equal(landing[0].id,'ESP_094047_1985');
assert(O.rendition(landing[0],P.DEFAULT_START,1200).fullDetail,'Use actual JP2 detail inside its crop extent');
assert(!O.rendition(landing[0],[18.59,77.40],1200).fullDetail,'Do not claim detailed coverage outside the detailed crop');
for(let i=1;i<landing.length;i++)assert(landing[i-1].captured_start>=landing[i].captured_start);
assert.equal(O.matches([0,0],catalog).length,0,'Outside observations must not get nearest images as exact matches');
assert(catalog.surface.find(o=>o.association==='regional_context').coordinate===null);
assert(catalog.ctx.captured_start===null,'Unknown mosaic capture dates must remain unknown');
assert(catalog.orbital.every(o=>o.published===null&&o.product_created&&o.captured_start),'Product creation is separate from public release');
const result=P.plan(P.DEFAULT_START,P.DEFAULT_GOAL),stops=O.checkpoints(result.path,P);
assert.equal(stops[0].index,0);assert.equal(stops.at(-1).index,result.path.length-1);
assert.equal(new Set(stops.map(c=>c.index)).size,stops.length);
assert(stops.every(c=>!c.reviewed&&c.note===''));
const steep=stops.find(c=>c.title.includes('Slope review'));
assert(steep);assert.equal(P.sample(steep.p).maxSlope,Math.max(...result.path.map(p=>P.sample(p).maxSlope)));
for(const c of stops)assert.deepEqual(c.p,result.path[c.index]);
assert(O.checkpoints([P.DEFAULT_START,P.DEFAULT_GOAL],P).length===2,'Short routes collapse duplicate stops');
const b=catalog.ctx.bbox;assert.deepEqual(O.pixel([b.lat1,b.lon0],b,900,600),[0,0]);
assert.deepEqual(O.pixel([b.lat0,b.lon1],b,900,600),[900,600]);
const projectedMidLat=(2*Math.atan(Math.exp((Math.log(Math.tan(Math.PI/4+b.lat0*Math.PI/360))+Math.log(Math.tan(Math.PI/4+b.lat1*Math.PI/360)))/2))-Math.PI/2)*180/Math.PI;
assert(Math.abs(O.pixel([projectedMidLat,(b.lon0+b.lon1)/2],b,900,600)[1]-300)<1e-7);
console.log('Observation checks passed: footprint holes, exact coverage, date semantics, rover associations, route checkpoints and Mercator placement.');
